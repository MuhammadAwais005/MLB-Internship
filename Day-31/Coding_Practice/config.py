"""
Shared settings for all Day 31 scripts.

The dataset is "ppe" v2 from Roboflow Universe (anjrh81/ppe-asmsk, CC BY 4.0),
exported in YOLO format. Roboflow published the classes only as '0'..'3';
their meaning was identified by looking at the labelled boxes
(see 01_explore_dataset.py -> outputs/exploration/class_examples.jpg).
"""

from pathlib import Path

import yaml

BASE_DIR = Path(__file__).resolve().parent
DATASET_DIR = BASE_DIR / "Dataset"
ORIGINAL_YAML = DATASET_DIR / "data.yaml"      # as downloaded from Roboflow (left untouched)
FIXED_YAML = BASE_DIR / "dataset.yaml"         # the one we train with

OUTPUT_DIR = BASE_DIR / "outputs"
EXPLORE_DIR = OUTPUT_DIR / "exploration"
TRAIN_DIR = OUTPUT_DIR / "training"           # Ultralytics run folders go here
EVAL_DIR = OUTPUT_DIR / "evaluation"
INFER_DIR = OUTPUT_DIR / "inference"
MODEL_DIR = BASE_DIR / "models"

RUN_NAME = "ppe_yolo11n"
BEST_MODEL = MODEL_DIR / "ppe_yolo11n_best.pt"

SPLITS = ("train", "valid", "test")

# Roboflow names -> what the boxes actually contain
CLASS_NAMES = {0: "helmet", 1: "boots", 2: "person", 3: "vest"}
CLASS_COLORS = {0: (0, 165, 255), 1: (180, 105, 255), 2: (255, 160, 0), 3: (0, 220, 120)}  # BGR


def write_dataset_yaml():
    """
    Writes dataset.yaml for training. Two problems in the Roboflow file are fixed:

    1. Paths: Roboflow writes 'train: ../train/images'. Ultralytics resolves
       such paths from the dataset root, so '../' points one folder too high
       and training stops with "images not found". We set an absolute 'path'
       and plain 'train/images' etc., which works on any computer.
    2. Names: '0', '1', '2', '3' become helmet, boots, person, vest, so plots,
       metrics and predictions are readable.
    """
    original = yaml.safe_load(ORIGINAL_YAML.read_text(encoding="utf-8"))
    config = {
        "path": str(DATASET_DIR),
        "train": "train/images",
        "val": "valid/images",
        "test": "test/images",
        "nc": original.get("nc", len(CLASS_NAMES)),
        "names": CLASS_NAMES,
    }
    with FIXED_YAML.open("w", encoding="utf-8") as f:
        f.write("# Generated by config.py from Dataset/data.yaml (Roboflow export)\n")
        yaml.safe_dump(config, f, sort_keys=False)
    return FIXED_YAML
